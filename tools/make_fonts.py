#!/usr/bin/env python3
"""Turn a TTF into anti-aliased bitmap fonts for Claude Buddy (buddy/aa_fonts.cpp).

  .venv/bin/python tools/make_fonts.py

Each glyph is stored at 4 bits per pixel (16 coverage levels), so the device can
blend text smoothly into whatever is behind it (buddy/aa.h). The fonts and
sizes are listed in FONTS below; re-run after changing them.

Font: Inter (tools/fonts/Inter.ttf), SIL Open Font License (tools/fonts/OFL.txt).
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, "fonts", "Inter.ttf")
ASCII = "".join(chr(c) for c in range(32, 127))

# name, pixel size, weight (100-900)
FONTS = [
    ("fontBig", 38, 700),     # usage percent, today's hero number
    ("fontClock", 26, 650),   # the time at the top
    ("fontTitle", 20, 700),   # "Claude is cooking"
    ("fontBody", 15, 600),    # card labels
    ("fontSmall", 13, 550),   # details, reset times
    ("fontTiny", 11, 600),    # chart labels, feed
]

def render(size, weight):
    font = ImageFont.truetype(TTF, size)
    font.set_variation_by_axes([min(32, max(14, size)), weight])
    glyphs, bitmap = [], bytearray()
    ascent, descent = font.getmetrics()
    for ch in ASCII:
        advance = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        nibbles = []
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            nibbles = [(v * 15 + 127) // 255 for v in img.tobytes()]
        if len(nibbles) % 2:
            nibbles.append(0)
        offset = len(bitmap)
        bitmap += bytes(nibbles[i] << 4 | nibbles[i + 1] for i in range(0, len(nibbles), 2))
        glyphs.append((offset, w, h, advance, l, t))
    return glyphs, bitmap, ascent, ascent + descent


def main():
    OUT = os.path.join(HERE, "..", "buddy", "aa_fonts.cpp")
    out = [
        "// Generated by tools/make_fonts.py from Inter (SIL Open Font License). Do not edit.",
        '#include "aa.h"',
        "",
    ]
    total = 0
    for name, size, weight in FONTS:
        glyphs, bitmap, ascent, line = render(size, weight)
        total += len(bitmap)
        out.append(f"static const uint8_t {name}Bits[] = {{")
        for i in range(0, len(bitmap), 24):
            out.append("  " + ",".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const AaGlyph {name}Glyphs[] = {{")
        for (offset, w, h, adv, dx, dy), ch in zip(glyphs, ASCII):
            out.append(f"  {{{offset}, {w}, {h}, {adv}, {dx}, {dy}}},  // {ch!r}")
        out.append("};")
        out.append(f"const AaFont {name} = {{{name}Bits, {name}Glyphs, 32, 126, {ascent}, {line}}};")
        out.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUT)}: {len(FONTS)} fonts, {total / 1024:.0f} KB of glyphs")


if __name__ == "__main__":
    main()
